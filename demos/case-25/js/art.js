function makeOpaque(canvas) {
    const ctx = canvas.getContext("2d");
    const data = ctx.getImageData(0, 0, canvas.width, canvas.height);
    for (let i = 3; i < data.data.length; i += 4) data.data[i] = 255;
    ctx.putImageData(data, 0, 0);
    return canvas;
}

