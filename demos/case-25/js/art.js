function water(ctx, w, h, y0, p, seed, reflectionX = .65) {
    const rand = mulberry32(seed);
    const g = ctx.createLinearGradient(0, y0, 0, h);
    g.addColorStop(0, p.water);
    g.addColorStop(.55, shade(p.water, -18));
    g.addColorStop(1, shade(p.water, -36));
    ctx.fillStyle = g;
    ctx.fillRect(0, y0, w, h - y0);
    const rx = w * reflectionX;
    const rg = ctx.createLinearGradient(rx - w * .07, 0, rx + w * .07, 0);
    rg.addColorStop(0, "rgba(250,228,181,0)");
    rg.addColorStop(.5, "rgba(250,228,181,0.3)");
    rg.addColorStop(1, "rgba(250,228,181,0)");
    ctx.fillStyle = rg;
    ctx.globalAlpha = .55;
    ctx.beginPath();
    ctx.moveTo(rx - w * .035, y0);
    ctx.lineTo(rx + w * .035, y0);
    ctx.lineTo(rx + w * .16, h);
    ctx.lineTo(rx - w * .16, h);
    ctx.closePath();
    ctx.fill();
    ctx.globalAlpha = 1;
    for (let i = 0; i < 120; i++) {
        const yy = y0 + Math.pow(rand(), .72) * (h - y0);
        const t = (yy - y0) / Math.max(1, h - y0);
        const xx = rand() * w;
        const len = w * (.004 + rand() * .035) * (.6 + t);
        ctx.strokeStyle = rand() > .76 ? p.foam + "66" : p.far + "3a";
        ctx.globalAlpha = .12 + rand() * .24;
        ctx.lineWidth = Math.max(.5, h * .0025 * (.7 + rand()));
        ctx.beginPath();
        ctx.moveTo(xx, yy);
        ctx.bezierCurveTo(xx + len * .35, yy - len * .12, xx + len * .7, yy + len * .1, xx + len, yy);
        ctx.stroke();
    }
    ctx.globalAlpha = 1;
}

function shade(hex, amt) {
    const n = parseInt(hex.slice(1), 16);
    let r = (n >> 16) + amt, g = (n >> 8 & 255) + amt, b = (n & 255) + amt;
    r = Math.max(0, Math.min(255, r));
    g = Math.max(0, Math.min(255, g));
    b = Math.max(0, Math.min(255, b));
    return "#" + (r << 16 | g << 8 | b).toString(16).padStart(6, "0");
}

