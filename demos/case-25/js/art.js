const TAU = Math.PI * 2;

function mulberry32(seed) {
    let a = seed >>> 0;
    return function() {
        a |= 0;
        a = a + 1831565813 | 0;
        let t = Math.imul(a ^ a >>> 15, 1 | a);
        t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t;
        return ((t ^ t >>> 14) >>> 0) / 4294967296;
    };
}

function newCanvas(w, h) {
    const c = document.createElement("canvas");
    c.width = w;
    c.height = h;
    return c;
}

function makeNoiseTile(seed = 1, size = 192, contrast = .5) {
    const c = newCanvas(size, size);
    const ctx = c.getContext("2d");
    const img = ctx.createImageData(size, size);
    const rand = mulberry32(seed);
    for (let i = 0; i < img.data.length; i += 4) {
        const v = 108 + (rand() - .5) * 155 * contrast;
        img.data[i] = v;
        img.data[i + 1] = v;
        img.data[i + 2] = v;
        img.data[i + 3] = 255;
    }
    ctx.putImageData(img, 0, 0);
    return c;
}

const NOISE_1 = makeNoiseTile(4, 256, .8);

const NOISE_2 = makeNoiseTile(17, 128, .45);

function makeGrainSpeckleTile(seed, size, light = true) {
    const c = newCanvas(size, size);
    const ctx = c.getContext("2d");
    const rand = mulberry32(seed);
    const img = ctx.createImageData(size, size);
    for (let i = 0; i < img.data.length; i += 4) {
        const lightSpot = rand() > .52;
        const v = lightSpot ? 226 + rand() * 27 : 12 + rand() * 38;
        const a = Math.pow(rand(), 3.2) * (light ? 100 : 80);
        img.data[i] = v;
        img.data[i + 1] = lightSpot ? v - 6 : v + 4;
        img.data[i + 2] = lightSpot ? v - 17 : v + 11;
        img.data[i + 3] = a;
    }
    ctx.putImageData(img, 0, 0);
    return c;
}

const GRAIN_LIGHT = makeGrainSpeckleTile(91, 192, true);

const GRAIN_DARK = makeGrainSpeckleTile(173, 160, false);

function grain(ctx, w, h, alpha = .085, mode = "overlay", tile = NOISE_1) {
    ctx.save();
    ctx.globalCompositeOperation = "source-over";
    ctx.globalAlpha = clampN(alpha * 1.3, .02, .7);
    ctx.fillStyle = ctx.createPattern(GRAIN_LIGHT, "repeat");
    ctx.fillRect(0, 0, w, h);
    ctx.globalAlpha = clampN(alpha * .72, .01, .5);
    ctx.fillStyle = ctx.createPattern(GRAIN_DARK, "repeat");
    ctx.fillRect(0, 0, w, h);
    ctx.restore();
}

function clampN(v, a, b) {
    return Math.max(a, Math.min(b, v));
}

function vignette(ctx, w, h, strength = .35, color = "rgba(5,10,12,") {
    const g = ctx.createRadialGradient(w * .48, h * .43, Math.min(w, h) * .16, w * .5, h * .5, Math.max(w, h) * .72);
    g.addColorStop(0, color + "0)");
    g.addColorStop(.7, color + (strength * .24).toFixed(3) + ")");
    g.addColorStop(1, color + strength.toFixed(3) + ")");
    ctx.fillStyle = g;
    ctx.fillRect(0, 0, w, h);
}

function paperWash(ctx, w, h, seed = 8, strength = .14) {
    const rand = mulberry32(seed);
    ctx.save();
    ctx.globalCompositeOperation = "source-over";
    for (let i = 0; i < 55; i++) {
        const y = rand() * h;
        ctx.strokeStyle = `rgba(247,234,205,${.004 + rand() * strength * .025})`;
        ctx.lineWidth = .6 + rand() * 8;
        ctx.beginPath();
        ctx.moveTo(-20, y);
        ctx.bezierCurveTo(w * .3, y + (rand() - .5) * 30, w * .7, y + (rand() - .5) * 30, w + 20, y + (rand() - .5) * 16);
        ctx.stroke();
    }
    ctx.restore();
}

